#!/usr/bin/env node
/* Publish the recorded Intel check cadence. Reads registries and the
 * scheduled functions. Does not invent a frequency for a source that has none.
 */
'use strict';
const fs = require('fs');

const FREQ_LABEL = {
  daily: 'Daily',
  twice_weekly: 'Twice a week',
  weekly: 'Weekly',
  event_driven: 'Event-driven'
};

function readJson(p) {
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

function esc(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function freqLabel(value) {
  if (value == null || String(value).trim() === '') return 'Not recorded';
  return FREQ_LABEL[value] || null;
}

function scheduleLine(toml, name) {
  const block = toml.split('[functions."' + name + '"]')[1] || '';
  const schedule = (block.match(/schedule\s*=\s*"([^"]+)"/) || [])[1] || '';
  return schedule;
}

const gcc = readJson('data/gcc-source-registry.json');
const registry = readJson('data/source-registry.json');
const toml = fs.readFileSync('netlify.toml', 'utf8');

const jobs = [
  { id: 'refresh-data', schedule: scheduleLine(toml, 'refresh-data') },
  { id: 'daily-rebuild', schedule: scheduleLine(toml, 'daily-rebuild') },
  { id: 'watchlist-alerts', schedule: scheduleLine(toml, 'watchlist-alerts') }
];
jobs.forEach(function (job) {
  if (!job.schedule) {
    console.error('missing schedule for ' + job.id);
    process.exit(1);
  }
});

const sources = [];
const seen = {};
(gcc.sources || []).forEach(function (s) {
  const label = freqLabel(s.crawl_frequency);
  if (!label) {
    console.error('unrecognised crawl_frequency on ' + s.source_id + ': ' + s.crawl_frequency);
    process.exit(1);
  }
  sources.push({
    source_id: s.source_id,
    organization: s.organization || s.source_id,
    country: s.country && String(s.country).trim() ? s.country : '',
    cadence: s.crawl_frequency,
    cadence_label: label,
    last_checked: s.last_checked || null,
    status: s.status || '',
    registry: 'gcc-source-registry'
  });
  seen[s.source_id] = 1;
});
(registry.sources || []).forEach(function (s) {
  if (seen[s.source_id]) return;
  sources.push({
    source_id: s.source_id,
    organization: s.name || s.organization || s.source_id,
    country: s.country && String(s.country).trim() ? s.country : '',
    cadence: s.crawl_frequency || null,
    cadence_label: freqLabel(s.crawl_frequency),
    last_checked: s.last_checked_at || s.last_checked || null,
    status: s.active === false ? 'inactive' : (s.status || ''),
    registry: 'source-registry'
  });
});

const byCountry = {};
sources.forEach(function (s) {
  const key = s.country || '';
  (byCountry[key] = byCountry[key] || []).push(s);
});
const countryKeys = Object.keys(byCountry).sort(function (a, b) {
  if (!a) return 1;
  if (!b) return -1;
  return a.localeCompare(b);
});

const doc = {
  $comment: 'GENERATED by build-intel-cadence.js from the source registries and netlify.toml schedules. Frequencies are copied from crawl_frequency. A source with no crawl_frequency is Not recorded.',
  generated_from: ['data/gcc-source-registry.json', 'data/source-registry.json', 'netlify.toml'],
  jobs: jobs,
  countries: countryKeys.map(function (key) {
    return {
      country: key || null,
      sources: byCountry[key]
    };
  })
};
fs.writeFileSync('data/intel-cadence.json', JSON.stringify(doc, null, 2) + '\n');

function rowsFor(list) {
  return list.map(function (s) {
    const checked = s.last_checked ? esc(s.last_checked) : 'Not checked';
    return '<tr><td>' + esc(s.organization) + '</td><td><code>' + esc(s.source_id) + '</code></td><td>' + esc(s.cadence_label) + '</td><td>' + checked + '</td><td>' + esc(s.status || '—') + '</td></tr>';
  }).join('\n');
}

const countryBlocks = countryKeys.map(function (key) {
  const label = key || 'Country not recorded';
  return '<h3>' + esc(label) + '</h3>\n' +
    '<table><tr><th>Source</th><th>Id</th><th>Check cadence</th><th>Last checked</th><th>Status</th></tr>\n' +
    rowsFor(byCountry[key]) + '\n</table>';
}).join('\n');

const jobRows = jobs.map(function (job) {
  return '<tr><td><code>' + esc(job.id) + '</code></td><td><code>' + esc(job.schedule) + '</code></td></tr>';
}).join('\n');

const html =
  '<h2 id="coverage-cadence">Intel coverage cadence</h2>\n' +
  '<p>This is how often each registered source is checked. The figure is the <code>crawl_frequency</code> on the source registry. A source with no frequency on file is marked <b>Not recorded</b>. Per-country coverage (what has been published, and when it was last sourced) stays on the <a href="markets.html">market pages</a>.</p>\n' +
  '<h3>Desk schedule</h3>\n' +
  '<p>These are the scheduled functions in <code>netlify.toml</code>. They are the desk clocks, not a per-source promise.</p>\n' +
  '<table><tr><th>Function</th><th>Schedule</th></tr>\n' + jobRows + '\n</table>\n' +
  countryBlocks + '\n';

function insert(file, before) {
  let s = fs.readFileSync(file, 'utf8');
  const start = '<!-- INTEL-CADENCE:START -->';
  const end = '<!-- INTEL-CADENCE:END -->';
  const block = start + '\n' + html + end;
  if (s.indexOf(start) >= 0 && s.indexOf(end) > s.indexOf(start)) {
    s = s.slice(0, s.indexOf(start)) + block + s.slice(s.indexOf(end) + end.length);
  } else if (s.indexOf(before) < 0) {
    console.error(file + ' missing insertion point ' + before);
    process.exit(1);
  } else {
    s = s.replace(before, block + '\n\n  ' + before);
  }
  fs.writeFileSync(file, s);
}

insert('methodology.html', '<h2>Corrections</h2>');

const pointer =
  '<p id="intel-cadence" style="margin:8px 0 0;font-size:.92rem">How often each source and country is checked is on the <a href="methodology.html#coverage-cadence">coverage cadence</a>. Per-country coverage stays on the market pages.</p>';
let intel = fs.readFileSync('intel.html', 'utf8');
if (intel.indexOf('id="intel-cadence"') < 0) {
  const stampClose = intel.indexOf('id="stamp"');
  const after = intel.indexOf('</div>', stampClose);
  if (stampClose < 0 || after < 0) {
    console.error('intel.html stamp not found');
    process.exit(1);
  }
  intel = intel.slice(0, after + 6) + '\n  ' + pointer + intel.slice(after + 6);
  fs.writeFileSync('intel.html', intel);
}

console.log('build-intel-cadence: ' + sources.length + ' sources across ' + countryKeys.length + ' country groups');
