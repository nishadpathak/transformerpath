/* build-gcc-source-coverage.js — measurable per-GCC-country source coverage.
 *
 * The reviewer's P0 ask: "Each country needs a measurable source-coverage
 * report" (source count, last-seen date, coverage status). The discovery
 * pipeline already produces per-country candidates (gcc-discovery-candidates)
 * and a registry (gcc-coverage-report); this derives the measurable layer:
 *
 *   per country: registered sources · candidates · published · held-for-review
 *                · last sourced date · coverage status (CURRENT/DELAYED/STALE)
 *
 * It makes the discovery→verification→publication funnel visible per country,
 * so a researcher can see each morning where coverage is lagging and where
 * candidates are stuck awaiting approval. Reads only; never invents dates.
 * Writes data/gcc-source-coverage.json.
 */
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const COVERAGE_LAG_DAYS = 10;  // matches lib/intel-freshness.js
const STALE_DAYS = 30;

function readJson(rel, fallback) {
  try { return JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8')); }
  catch (e) { return fallback; }
}

const COUNTRY_ALIAS = {
  'United Arab Emirates': 'UAE', 'UAE': 'UAE',
  'Saudi Arabia': 'Saudi', 'Saudi': 'Saudi', 'KSA': 'Saudi',
  'Kuwait': 'Kuwait', 'Oman': 'Oman', 'Bahrain': 'Bahrain', 'Qatar': 'Qatar'
};
const GCC = ['UAE', 'Saudi', 'Kuwait', 'Oman', 'Qatar', 'Bahrain'];

const today = new Date();
const todayIso = today.toISOString().slice(0, 10);

function daysSince(iso) {
  if (!iso) return null;
  return Math.round((Date.parse(todayIso + 'T00:00:00Z') - Date.parse(iso + 'T00:00:00Z')) / 86400000);
}
function statusFor(iso) {
  const d = daysSince(iso);
  if (d == null) return 'NO_COVERAGE';
  if (d < 0) return 'CURRENT';            // future-dated check tolerated as current
  if (d <= COVERAGE_LAG_DAYS) return 'CURRENT';
  if (d <= STALE_DAYS) return 'DELAYED';
  return 'STALE';
}

// "Last sourced" = when we actually observed/sourced the item, not a future
// tender close/award date. Use publication/update/source-checked dates <= today.
function lastSourcedOf(cand) {
  const d = cand.dates || {};
  const cands = [d.publication_date, d.update_date, d.source_checked_at, d.event_date]
    .filter(Boolean)
    .filter((x) => x <= todayIso);
  cands.sort();
  return cands[cands.length - 1] || null;
}

function main() {
  const candDoc = readJson('data/gcc-discovery-candidates.json', []);
  const candidates = Array.isArray(candDoc) ? candDoc : (candDoc.candidates || []);
  const coverage = readJson('data/gcc-coverage-report.json', { gcc_coverage: {} }).gcc_coverage || {};
  const registry = readJson('data/gcc-source-registry.json', { sources: [] });
  const regSources = registry.sources || registry.gcc_sources || [];

  const regByCountry = {};
  for (const s of regSources) {
    const k = COUNTRY_ALIAS[s.country] || s.country;
    if (k) regByCountry[k] = (regByCountry[k] || 0) + 1;
  }

  const perCountry = {};
  for (const g of GCC) {
    perCountry[g] = {
      country: g,
      sources_registered: (coverage[g] && coverage[g].sources_registered) || regByCountry[g] || 0,
      candidates: 0,
      published: 0,
      held_for_review: 0,
      rejected: 0,
      last_sourced: null,
      coverage_status: 'NO_COVERAGE'
    };
  }

  for (const c of candidates) {
    const k = COUNTRY_ALIAS[c.country] || c.country;
    if (!perCountry[k]) continue;
    const row = perCountry[k];
    row.candidates++;
    if (c.published_to_intel === true) row.published++;
    else if (/REJECT/i.test(c.publish_decision || c.reject_reason || '')) row.rejected++;
    else row.held_for_review++;
    const ls = lastSourcedOf(c);
    if (ls && (!row.last_sourced || ls > row.last_sourced)) row.last_sourced = ls;
  }

  let latestOverall = null;
  for (const g of GCC) {
    const row = perCountry[g];
    row.days_since_last_sourced = daysSince(row.last_sourced);
    row.coverage_status = row.candidates === 0 ? 'NO_COVERAGE' : statusFor(row.last_sourced);
    if (row.last_sourced && (!latestOverall || row.last_sourced > latestOverall)) latestOverall = row.last_sourced;
  }

  const totals = GCC.reduce((a, g) => {
    const r = perCountry[g];
    a.candidates += r.candidates; a.published += r.published; a.held_for_review += r.held_for_review; a.rejected += r.rejected;
    return a;
  }, { candidates: 0, published: 0, held_for_review: 0, rejected: 0 });

  const out = {
    $comment: 'GENERATED by build-gcc-source-coverage.js — measurable per-country discovery coverage. Not editorial content.',
    generated: new Date().toISOString(),
    today: todayIso,
    thresholds: { coverage_lag_days: COVERAGE_LAG_DAYS, stale_days: STALE_DAYS },
    latest_sourced_overall: latestOverall,
    totals,
    publish_funnel_note:
      totals.published === 0 && totals.candidates > 0
        ? totals.candidates + ' candidates discovered but 0 published — items are awaiting the verification/publication step (publish_decision=HOLD_FOR_REVIEW).'
        : null,
    countries: GCC.map((g) => perCountry[g])
  };
  fs.writeFileSync(path.join(ROOT, 'data', 'gcc-source-coverage.json'), JSON.stringify(out, null, 2) + '\n');

  // Report
  console.log('GCC SOURCE COVERAGE (today ' + todayIso + ')');
  console.log('  country  sources  cand  pub  held  last-sourced  status');
  for (const g of GCC) {
    const r = perCountry[g];
    console.log(
      '  ' + g.padEnd(8) + ' ' + String(r.sources_registered).padStart(6) + '  ' +
      String(r.candidates).padStart(4) + '  ' + String(r.published).padStart(3) + '  ' +
      String(r.held_for_review).padStart(4) + '  ' + String(r.last_sourced || '—').padEnd(12) + '  ' + r.coverage_status
    );
  }
  console.log('  totals: candidates=' + totals.candidates + ' published=' + totals.published + ' held=' + totals.held_for_review);
  if (out.publish_funnel_note) console.log('  ⚠ ' + out.publish_funnel_note);
  console.log('build-gcc-source-coverage.js wrote data/gcc-source-coverage.json');
}

main();
