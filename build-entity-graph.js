#!/usr/bin/env node
/* build-entity-graph.js — central entity-relationship data (the knowledge graph).
 *
 * Reads the existing datasets and emits data/entity-graph.json: a single,
 * generated blueprint of how TransformerPath entities connect, so the internal
 * linking graph is maintained in ONE place and every page can pull consistent
 * "related" relationships without hand-editing thousands of links.
 *
 * Relationships captured:
 *   - country  -> manufacturers, grid operators, region, grid freq/sync
 *   - region   -> countries, manufacturers, intel items, events
 *   - type     -> manufacturers serving it (power/distribution/dry-type)
 *   - event    -> country, region, link
 * Run: node build-entity-graph.js  (part of the Netlify build command).
 */
'use strict';
const fs = require('fs');
const r = function (f) { return JSON.parse(fs.readFileSync(f, 'utf8')); };

const MANUF = r('data/manufacturers.json');
const GRIDS = r('data/grids.json');
const EVENTS = r('data/events.json');
const INTEL = r('data/intel.json');
const STATS = r('data/site-stats.json');

const byCountry = {};
MANUF.forEach(function (c) {
  byCountry[c.country] = byCountry[c.country] || { manufacturers: 0, region: c.region, flag: c.flag };
  byCountry[c.country].manufacturers += c.makers.filter(function (m) { return !/^Served by/i.test(m[0]); }).length;
  const types = new Set();
  c.makers.forEach(function (m) { String(m[3] || '').split(',').map(function (x) { return x.trim(); }).filter(Boolean).forEach(function (t) { types.add(t); }); });
  byCountry[c.country].types = [...types];
});
GRIDS.forEach(function (g) {
  byCountry[g.country] = byCountry[g.country] || { manufacturers: 0, region: g.region, flag: g.flag };
  byCountry[g.country].region = g.region; byCountry[g.country].flag = g.flag;
  byCountry[g.country].grid = { freq: g.freq, sync: g.sync, operators: g.grids.map(function (x) { return x[0]; }) };
});

const typeSets = { PT: [], DT: [], DRY: [] };
MANUF.forEach(function (c) {
  c.makers.forEach(function (m) {
    if (/^Served by/i.test(m[0])) return;
    const t = String(m[3] || '').toUpperCase().split(',').map(function (x) { return x.trim(); });
    t.forEach(function (k) { if (typeSets[k]) typeSets[k].push(m[0]); });
  });
});
Object.keys(typeSets).forEach(function (k) { typeSets[k] = [...new Set(typeSets[k])].sort(); });

const regionNames = [...new Set([...MANUF.map(function (c) { return c.region; }), ...GRIDS.map(function (g) { return g.region; })])];
const regions = {};
regionNames.forEach(function (rg) {
  const countries = [...new Set([...MANUF.filter(function (c) { return c.region === rg; }).map(function (c) { return c.country; }),
    ...GRIDS.filter(function (g) { return g.region === rg; }).map(function (g) { return g.country; })])];
  const manuf = MANUF.filter(function (c) { return c.region === rg; }).reduce(function (s, c) { return s + c.makers.filter(function (m) { return !/^Served by/i.test(m[0]); }).length; }, 0);
  regions[rg] = { countries: countries.length, manufacturers: manuf, countriesList: countries };
});

const countryEvents = {};
EVENTS.forEach(function (ev) {
  const co = ev.co || ev.c; (countryEvents[co] = countryEvents[co] || []).push({ n: ev.n, s: ev.s, u: ev.u, region: ev.r });
});

const graph = {
  _comment: 'Generated by build-entity-graph.js — single source for the internal linking graph. Do not edit by hand.',
  generated: new Date().toISOString().slice(0, 10),
  counters: { manufacturers: STATS.manufacturers, manufacturingCountries: STATS.manufacturingCountries, countries: STATS.countries, gridOperators: STATS.gridOperators, events: STATS.events },
  country: byCountry,
  region: regions,
  type: typeSets,
  // per-country upcoming events (top 5 by date)
  countryEvents: Object.fromEntries(Object.entries(countryEvents).map(function (e) { return [e[0], e[1].slice(0, 5)]; })),
};
fs.writeFileSync('data/entity-graph.json', JSON.stringify(graph, null, 2));
// concise summary
console.log('entity-graph.json wrote',
  Object.keys(graph.country).length, 'countries |',
  Object.keys(graph.region).length, 'regions |',
  Object.keys(graph.type).length, 'types |',
  Object.keys(graph.countryEvents).length, 'countries with events');
